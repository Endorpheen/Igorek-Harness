"""Generate client catalogues from the canonical error contract; no runtime I/O."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def outputs():
    catalog = json.loads((ROOT/'factory/config/error-catalog.json').read_text(encoding='utf-8'))
    encoded = json.dumps(catalog, ensure_ascii=False, indent=2) + '\n'
    kotlin = ['// Generated by tools/generate_error_contract.py; edit the canonical JSON.',
              'package ru.igorek.remote.data', '',
              'internal data class ErrorDefinition(val category: String, val action: String, val severity: String, val retryable: Boolean, val ru: String, val en: String)',
              'internal object ErrorCatalog {', '    const val schemaVersion = 1',
              f'    const val stableAfterMs = {catalog["stable_after_ms"]}L', '    val codes = mapOf(']
    for code, row in catalog['codes'].items():
        values = [json.dumps(row[k], ensure_ascii=False) if k != 'retryable' else str(row[k]).lower() for k in ('category', 'action', 'severity', 'retryable', 'ru', 'en')]
        kotlin.append('        '+json.dumps(code)+' to ErrorDefinition('+', '.join(values)+'),')
    kotlin.extend(['    )', '}', ''])
    return {
        'desktop/error-catalog.json': encoded,
        'factory/web_ui/static/error-catalog.js': '// Generated by tools/generate_error_contract.py.\nwindow.IgorekErrorCatalog = '+encoded.strip()+';\n',
        'android/app/src/main/java/ru/igorek/remote/data/ErrorCatalog.kt': '\n'.join(kotlin),
        'desktop/error-diagnostics.js': (ROOT/'factory/web_ui/static/error-diagnostics.js').read_text(encoding='utf-8'),
    }


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for name, content in outputs().items():
        path = ROOT/name
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != content:
                stale.append(name)
        else:
            path.write_text(content, encoding='utf-8')
    if stale:
        raise SystemExit('Regenerate error contracts: '+', '.join(stale))
