#!/usr/bin/env bash
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PORT="${FACTORY_PORT:-8181}"
DATA_DIR="${FACTORY_DATA_DIR:-$HOME/.igorek-agent-factory}"
POLICY="${FACTORY_BOLTBOOK_AUTONOMOUS_POLICY:-balanced}"
COMMENT_PROFILE="${FACTORY_BOLTBOOK_AUTONOMOUS_PROFILE:-codex}"
POST_PROFILE="${FACTORY_BOLTBOOK_AUTONOMOUS_POST_PROFILE:-codex}"
SUBMOLT="${FACTORY_BOLTBOOK_AUTONOMOUS_POST_SUBMOLT:-general}"

cd "$REPO_ROOT"

export FACTORY_DATA_DIR="$DATA_DIR"
export FACTORY_BOLTBOOK_HEARTBEAT_ENABLED="${FACTORY_BOLTBOOK_HEARTBEAT_ENABLED:-true}"
export FACTORY_BOLTBOOK_AUTONOMOUS_COMMENTS_ENABLED="${FACTORY_BOLTBOOK_AUTONOMOUS_COMMENTS_ENABLED:-true}"
export FACTORY_BOLTBOOK_AUTONOMOUS_POSTS_ENABLED="${FACTORY_BOLTBOOK_AUTONOMOUS_POSTS_ENABLED:-true}"
export FACTORY_BOLTBOOK_AUTONOMOUS_POLICY="$POLICY"
export FACTORY_BOLTBOOK_AUTONOMOUS_PROFILE="$COMMENT_PROFILE"
export FACTORY_BOLTBOOK_AUTONOMOUS_POST_PROFILE="$POST_PROFILE"
export FACTORY_BOLTBOOK_AUTONOMOUS_POST_SUBMOLT="$SUBMOLT"

echo "[run-mini] repo_root=$REPO_ROOT"
echo "[run-mini] data_dir=$FACTORY_DATA_DIR"
echo "[run-mini] port=$PORT"
echo "[run-mini] policy=$FACTORY_BOLTBOOK_AUTONOMOUS_POLICY"
echo "[run-mini] comment_profile=$FACTORY_BOLTBOOK_AUTONOMOUS_PROFILE"
echo "[run-mini] post_profile=$FACTORY_BOLTBOOK_AUTONOMOUS_POST_PROFILE"
echo "[run-mini] submolt=$FACTORY_BOLTBOOK_AUTONOMOUS_POST_SUBMOLT"

exec python3 factory_api.py --port "$PORT"
