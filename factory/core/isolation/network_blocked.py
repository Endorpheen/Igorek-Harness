"""Blocked-host diagnostics for the per-session egress ruleset (plan todo 16).

Every deny rule generated by :mod:`factory.core.isolation.network` logs with the
stable :data:`BLOCKED_HOST_LOG_PREFIX` before dropping, so a guest that hits the
wall produces a kernel-log line instead of a silent hang. This module turns such
a line into :class:`BlockedHostEvent`, wraps it into the taxonomy-valid
``isolation.blocked_host`` trace record (:func:`blocked_host_record`) and appends
those records to the authoritative host trace file through the same writer the
trace relay uses.

:class:`BlockedHostWatcher` is the runtime caller (plan todo 40b): it drains the
guest kernel log through an injected line source and emits one record per denial,
so the guest runner's trace stream carries ``isolation.blocked_host`` to the host
instead of the event existing only in a test. :class:`KernelLogSource` is the
production source: ``dmesg --follow`` in a reader thread (the guest image sets
``kernel.dmesg_restrict = 0`` so the unprivileged agent user can read the ring).

Parsing is deliberately tolerant: unrelated kernel chatter and truncated lines
yield ``None``/are skipped, and a failed append loses one record with a warning.
A diagnostic concern must never raise into the dispatch loop.
"""

from __future__ import annotations

import logging
import os
import queue
import re
import subprocess
import threading
from collections.abc import Callable, Iterable, Mapping, Sequence
from dataclasses import dataclass
from typing import Any, Final

from ..cc_backend_trace import append_cc_backend_trace
from ..trace_taxonomy import CcTraceEvent, trace_event

logger = logging.getLogger(__name__)

__all__ = [
    "BLOCKED_HOST_LOG_PREFIX",
    "BLOCKED_HOST_REASON",
    "BlockedHostEvent",
    "BlockedHostWatcher",
    "KernelLogSource",
    "LineSource",
    "TraceWriter",
    "blocked_host_record",
    "emit_blocked_host_lines",
    "parse_blocked_host_line",
]

#: Kernel-log prefix every deny rule carries; the pairing is pinned by tests.
BLOCKED_HOST_LOG_PREFIX: Final[str] = "igorek-egress-blocked: "
BLOCKED_HOST_REASON: Final[str] = "egress_denied"

_FIELD_RE: Final[re.Pattern[str]] = re.compile(r"\b(SRC|DST|PROTO|SPT|DPT)=([^\s]+)")

TraceWriter = Callable[[str, dict[str, Any]], None]
#: Returns only the lines not handed over yet (never a full re-read).
LineSource = Callable[[], tuple[str, ...]]


@dataclass(frozen=True, slots=True)
class BlockedHostEvent:
    """One egress attempt the guest ruleset denied."""

    destination: str
    protocol: str
    port: int | None
    source: str
    source_port: int | None
    pinned_host: str = ""


def parse_blocked_host_line(
    line: str, *, pinned_hosts: Mapping[str, str] | None = None
) -> BlockedHostEvent | None:
    """Parse one kernel-log denial line; unrelated lines yield ``None``.

    ``pinned_hosts`` maps a pinned address back to the allow host it belongs to,
    which names the blocked host in the event when the denied address was part of
    the allowlist (an address the session legitimately needs but that was
    rejected by the explicit host/LAN/metadata denies).
    """
    if BLOCKED_HOST_LOG_PREFIX not in line:
        return None
    fields: dict[str, str] = {}
    for match in _FIELD_RE.finditer(line):
        fields.setdefault(match.group(1), match.group(2))
    destination = fields.get("DST", "")
    protocol = fields.get("PROTO", "")
    if not destination or not protocol:
        return None
    mapping = pinned_hosts or {}
    return BlockedHostEvent(
        destination=destination,
        protocol=protocol.lower(),
        port=_int_or_none(fields.get("DPT")),
        source=fields.get("SRC", ""),
        source_port=_int_or_none(fields.get("SPT")),
        pinned_host=str(mapping.get(destination, "")),
    )


def blocked_host_record(event: BlockedHostEvent) -> dict[str, Any]:
    """The taxonomy-valid trace record for one denied egress attempt."""
    return trace_event(
        CcTraceEvent.ISOLATION_BLOCKED_HOST,
        destination=event.destination,
        port=event.port,
        protocol=event.protocol,
        source=event.source,
        source_port=event.source_port,
        pinned_host=event.pinned_host,
        reason=BLOCKED_HOST_REASON,
    )


def emit_blocked_host_lines(
    workdir: str | os.PathLike[str],
    lines: Iterable[str],
    *,
    pinned_hosts: Mapping[str, str] | None = None,
    writer: TraceWriter = append_cc_backend_trace,
) -> tuple[BlockedHostEvent, ...]:
    """Append one ``isolation.blocked_host`` record per denial line."""
    events: list[BlockedHostEvent] = []
    for line in lines:
        event = parse_blocked_host_line(line, pinned_hosts=pinned_hosts)
        if event is None:
            continue
        try:
            writer(str(workdir), blocked_host_record(event))
        except OSError as exc:
            logger.warning(
                "isolation network: cannot append a blocked_host record: %s", exc
            )
            continue
        events.append(event)
    return tuple(events)


def _int_or_none(raw: str | None) -> int | None:
    if raw is None:
        return None
    try:
        return int(raw, 10)
    except ValueError:
        return None


class BlockedHostWatcher:
    """Drain new kernel-log lines into ``isolation.blocked_host`` records.

    The runtime caller of :func:`emit_blocked_host_lines` (plan todo 40b): the
    guest runner polls it while a turn runs, so a denied probe becomes a trace
    record the runner streams to the host - not a diagnostic that only exists in
    a unit test. ``source`` hands over only lines not seen before, and a failing
    source loses diagnostics with a warning, never the run.
    """

    def __init__(
        self,
        workdir: str | os.PathLike[str],
        source: LineSource,
        *,
        pinned_hosts: Mapping[str, str] | None = None,
        writer: TraceWriter = append_cc_backend_trace,
    ) -> None:
        self._workdir = str(workdir)
        self._source = source
        self._pinned = dict(pinned_hosts or {})
        self._writer = writer
        self.emitted = 0

    def poll(self) -> tuple[BlockedHostEvent, ...]:
        """Emit one record per new denial line; never raises into the loop."""
        try:
            lines = tuple(self._source())
        except OSError as exc:
            logger.warning("isolation network: kernel-log source failed: %s", exc)
            return ()
        events = emit_blocked_host_lines(
            self._workdir, lines, pinned_hosts=self._pinned, writer=self._writer
        )
        self.emitted += len(events)
        return events


class KernelLogSource:
    """Incremental kernel-log lines from ``dmesg --follow`` (guest side).

    ``start()`` raises ``OSError`` when the log is not readable: the caller
    reports the loss of diagnostics and keeps enforcing the ruleset.
    """

    def __init__(
        self, command: Sequence[str] = ("dmesg", "-w"), *, max_lines: int = 4096
    ) -> None:
        self._command = tuple(command)
        self._lines: queue.Queue[str] = queue.Queue(maxsize=max_lines)
        self._process: subprocess.Popen[str] | None = None
        self._thread: threading.Thread | None = None

    def start(self) -> None:
        process = subprocess.Popen(
            list(self._command),
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            text=True,
            errors="replace",
        )
        self._process = process
        self._thread = threading.Thread(
            target=self._pump,
            args=(process,),
            name="igorek-kernel-log",
            daemon=True,
        )
        self._thread.start()

    def __call__(self) -> tuple[str, ...]:
        lines: list[str] = []
        while True:
            try:
                lines.append(self._lines.get_nowait())
            except queue.Empty:
                return tuple(lines)

    def close(self) -> None:
        process = self._process
        self._process = None
        if process is not None:
            try:
                process.terminate()
                process.wait(timeout=2.0)
            except OSError:
                pass
            except subprocess.TimeoutExpired:
                try:
                    process.kill()
                except OSError:
                    pass
        if self._thread is not None:
            self._thread.join(timeout=2.0)
            self._thread = None

    def _pump(self, process: subprocess.Popen[str]) -> None:
        stream = process.stdout
        if stream is None:
            return
        for line in stream:
            try:
                self._lines.put_nowait(line.rstrip("\n"))
            except queue.Full:
                logger.warning("isolation network: dropping a kernel-log line")
