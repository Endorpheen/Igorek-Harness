"""Server access to OpenAI Realtime: key from Vault, ephemeral secret, SDP.

The long-lived `OPENAI_API_KEY` is read only here and never leaves the host.
The ephemeral secret is generated by the server and used for server-side SDP exchange; the browser does not see any of them. Errors do not include the key or the upstream response body.
"""

from __future__ import annotations

import json
import os
import threading
import time
import urllib.error
import urllib.request
from typing import Any

from . import config as rt_config

_USER_AGENT = "IgorekFactory realtime-voice"
_TIMEOUT_S = 15.0
_KEY_TTL_S = 600.0
_LOCK = threading.Lock()
_KEY_CACHE: dict[str, Any] = {"at": 0.0, "key": ""}


class RealtimeError(Exception):
    """Typed real-time error: error code is sent in JSON, not as a 500 status."""

    def __init__(self, code: str, status: int, message: str) -> None:
        super().__init__(message)
        self.code = code
        self.status = status
        self.message = message


def openai_api_key() -> str:
    """The OpenAI API key is fully hosted on the server ('' is unavailable). The value is not logged."""
    env_key = str(os.environ.get("OPENAI_API_KEY") or "").strip()
    if env_key:
        return env_key
    now = time.monotonic()
    with _LOCK:
        cached = str(_KEY_CACHE.get("key") or "")
        if cached and now - float(_KEY_CACHE.get("at") or 0.0) < _KEY_TTL_S:
            return cached
    try:
        from ..vault.runtime import build_services
        services = build_services(prompt=False)
    except Exception:
        return ""
    candidates = [
        rt_config.agent_id(),
        str(os.environ.get("FACTORY_VAULT_AGENT") or "").strip(),
        "codex",
    ]
    seen: list[str] = []
    for agent in candidates:
        if not agent or agent in seen:
            continue
        seen.append(agent)
        try:
            decision = services.broker.get_ephemeral_env(
                service="openai", agent_id=agent, ttl=rt_config.ttl_seconds()
            )
        except Exception:
            continue
        if not getattr(decision, "allowed", False):
            continue
        value = str((getattr(decision, "env", None) or {}).get("OPENAI_API_KEY") or "").strip()
        if value:
            with _LOCK:
                _KEY_CACHE.update({"at": now, "key": value})
            return value
    return ""


def _http_error(exc: urllib.error.HTTPError) -> RealtimeError:
    if exc.code == 401:
        return RealtimeError("key_rejected", 502, "OpenAI отклонил ключ Realtime")
    if exc.code == 429:
        return RealtimeError("rate_limited", 502, "OpenAI ограничил запросы Realtime")
    return RealtimeError("upstream", 502, f"OpenAI Realtime ответил ошибкой {exc.code}")


def _post_json(url: str, *, payload: dict[str, Any], bearer: str, timeout: float = _TIMEOUT_S) -> dict[str, Any]:
    data = json.dumps(payload, ensure_ascii=False).encode("utf-8")
    request = urllib.request.Request(
        url,
        data=data,
        method="POST",
        headers={
            "Authorization": f"Bearer {bearer}",
            "Content-Type": "application/json",
            "Accept": "application/json",
            "User-Agent": _USER_AGENT,
        },
    )
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            raw = response.read()
    except urllib.error.HTTPError as exc:
        raise _http_error(exc) from exc
    except (urllib.error.URLError, TimeoutError, OSError) as exc:
        raise RealtimeError("network", 502, "Не удалось связаться с OpenAI Realtime") from exc
    try:
        value = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise RealtimeError("invalid_response", 502, "OpenAI Realtime вернул некорректный ответ") from exc
    if not isinstance(value, dict):
        raise RealtimeError("invalid_response", 502, "OpenAI Realtime вернул некорректный ответ")
    return value


def mint_client_secret(
    *, session_payload: dict[str, Any], ttl_s: int, key: str, base_url: str | None = None
) -> dict[str, Any]:
    """Create an ephemeral session secret; returns only `value`/`expires_at`."""
    base = base_url or rt_config.base_url()
    payload = {
        "expires_after": {"anchor": "created_at", "seconds": int(ttl_s)},
        "session": session_payload,
    }
    value = _post_json(f"{base}/v1/realtime/client_secrets", payload=payload, bearer=key)
    secret = str(value.get("value") or "")
    if not secret:
        raise RealtimeError("invalid_response", 502, "OpenAI Realtime не вернул клиентский секрет")
    return {"value": secret, "expires_at": value.get("expires_at")}


def create_call(*, sdp: str, ephemeral: str, base_url: str | None = None) -> dict[str, str]:
    """Send the SDP offer to OpenAI and return the SDP answer along with the provider call ID."""
    base = base_url or rt_config.base_url()
    data = str(sdp or "").encode("utf-8")
    if not data or b"v=0" not in data or b"m=audio" not in data:
        raise RealtimeError("invalid_sdp", 400, "Некорректное SDP-предложение")
    request = urllib.request.Request(
        f"{base}/v1/realtime/calls",
        data=data,
        method="POST",
        headers={
            "Authorization": f"Bearer {ephemeral}",
            "Content-Type": "application/sdp",
            "Accept": "application/sdp",
            "User-Agent": _USER_AGENT,
        },
    )
    try:
        with urllib.request.urlopen(request, timeout=_TIMEOUT_S) as response:
            answer = response.read().decode("utf-8", "replace")
            location = str(response.headers.get("Location") or "")
    except urllib.error.HTTPError as exc:
        raise _http_error(exc) from exc
    except (urllib.error.URLError, TimeoutError, OSError) as exc:
        raise RealtimeError("network", 502, "Не удалось установить WebRTC-соединение с OpenAI") from exc
    if not answer or "v=0" not in answer or "m=audio" not in answer:
        raise RealtimeError("invalid_response", 502, "OpenAI Realtime вернул некорректный SDP-ответ")
    provider_call_id = location.rstrip("/").rsplit("/", 1)[-1] if location else ""
    return {"sdp": answer, "call_id": provider_call_id}


def hangup(*, provider_call_id: str, key: str, base_url: str | None = None) -> None:
    """Best-effort call termination on the OpenAI side; errors are silently swallowed."""
    if not provider_call_id or not key:
        return
    base = base_url or rt_config.base_url()
    request = urllib.request.Request(
        f"{base}/v1/realtime/calls/{provider_call_id}/hangup",
        data=b"",
        method="POST",
        headers={"Authorization": f"Bearer {key}", "User-Agent": _USER_AGENT},
    )
    try:
        with urllib.request.urlopen(request, timeout=_TIMEOUT_S):
            pass
    except Exception:
        return
